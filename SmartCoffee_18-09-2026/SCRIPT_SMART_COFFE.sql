USE SMART_COFFEE;

-- TABELA CLIENTES
CREATE TABLE IF NOT EXISTS CLIENTES (
    ID_CLIENTE INT AUTO_INCREMENT PRIMARY KEY,
    NOME_CLIENTE VARCHAR(60) NOT NULL,
    CPF VARCHAR(14) NOT NULL UNIQUE,
    TELEFONE VARCHAR(15),
    CONVENIO ENUM('SIM', 'NÃO') NOT NULL DEFAULT 'NÃO',
    EMAIL VARCHAR(90) NOT NULL,
    DATA_CADASTRO DATE NOT NULL
);

-- TABELA FUNCIONARIOS
CREATE TABLE IF NOT EXISTS FUNCIONARIOS (
    ID_FUNCIONARIO INT AUTO_INCREMENT PRIMARY KEY,
    NOME_FUNCIONARIO VARCHAR(60) NOT NULL,
    CPF VARCHAR(14) NOT NULL UNIQUE,
    SALARIO DECIMAL(10,2) NOT NULL,
    TELEFONE VARCHAR(15),
    CARGO VARCHAR(40) NOT NULL,
    DATA_ADMISSAO DATE NOT NULL
);

-- TABELA ESTOQUE
CREATE TABLE IF NOT EXISTS ESTOQUE (
    ID_INSUMO INT AUTO_INCREMENT PRIMARY KEY,
    NOME_INSUMO VARCHAR(60) NOT NULL,
    QUANTIDADE_ATUAL INT NOT NULL DEFAULT 0,
    PRECO DECIMAL(10,2) NOT NULL,
    UNIDADE_MEDIDA VARCHAR(10) NOT NULL,
    QUANTIDADE_MINIMA INT NOT NULL DEFAULT 0
);

-- TABELA PRODUTOS
CREATE TABLE IF NOT EXISTS PRODUTOS (
    ID_PRODUTO INT AUTO_INCREMENT PRIMARY KEY,
    NOME_PRODUTO VARCHAR(60) NOT NULL,
    PRECO_UNITARIO DECIMAL(10,2) NOT NULL,
    CATEGORIA VARCHAR(30) NOT NULL,
    DESCRICAO VARCHAR(180)
);

-- TABELA PAGAMENTOS
CREATE TABLE IF NOT EXISTS PAGAMENTOS (
    ID_PAGAMENTO INT AUTO_INCREMENT PRIMARY KEY,
    FORMA_PAGAMENTO VARCHAR(50) NOT NULL,
    VALOR DECIMAL(10,2) NOT NULL,          
    DATA_PAGAMENTO DATETIME DEFAULT CURRENT_TIMESTAMP, 
    STATUS_PAGAMENTO VARCHAR(20) DEFAULT 'PENDENTE'  
);

-- TABELA PEDIDOS
CREATE TABLE IF NOT EXISTS PEDIDOS (
    ID_PEDIDO INT AUTO_INCREMENT PRIMARY KEY,
    QUANTIDADE INT NOT NULL DEFAULT 1,
    DATA_HORA DATETIME DEFAULT CURRENT_TIMESTAMP,
    TIPO_PEDIDO VARCHAR(50) NOT NULL,
    STATUS VARCHAR(40) NOT NULL DEFAULT 'PENDENTE',
    VALOR_TOTAL DECIMAL(10,2) NOT NULL
);

-- TABELA DELIVERY
CREATE TABLE IF NOT EXISTS DELIVERY (
    ID_DELIVERY INT AUTO_INCREMENT PRIMARY KEY,
    ID_PEDIDO INT NOT NULL,                  
    ENDERECO_ENTREGA VARCHAR(255) NOT NULL,   
    TAXA_ENTREGA DECIMAL(10,2) DEFAULT 0.00,
    STATUS_DELIVERY VARCHAR(30) DEFAULT 'EM_PREPARACAO',
    NOME_ENTREGADOR VARCHAR(100),            
    DATA_ENVIO DATETIME,                    
    DATA_ENTREGA DATETIME,
    FOREIGN KEY (ID_PEDIDO) REFERENCES PEDIDOS(ID_PEDIDO)
);

-- TABELA PROGRAMA DE FIDELIDADE 
CREATE TABLE IF NOT EXISTS PGR_FIDELIDADE (
    ID_FIDELIDADE INT AUTO_INCREMENT PRIMARY KEY,
    ID_CLIENTE INT NOT NULL UNIQUE,
    SALDO_PONTOS INT NOT NULL DEFAULT 0, 
    DATA_ULTIMA_ATUALIZACAO DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    FOREIGN KEY (ID_CLIENTE) REFERENCES CLIENTES(ID_CLIENTE)
);
