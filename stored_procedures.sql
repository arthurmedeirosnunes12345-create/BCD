CREATE PROCEDURE ADICIONAR_ITEM_PEDIDO (
    IN P_PRODUTO INT,
    IN P_ID_QUANTIDADE INT,
    IN P_QUANTIDADE INT
)
BEGIN  
    DECLARE V_PRECO DECIMAL (10,2);
    IF P_QUANTIDADE <= 0 THEN 
        SELECT 'QUANTIDADE INVÁLIDA' AS MENSAGEM;
    ELSE    
        SELECT PRECO 
        INTO V_PRECO
        FROM PRODUTO
        WHERE ID_PRODUTO = P_ID_PRODUTO
            AND ATIVO= TRUE;

        INSERT INTO ITEM_PEDIDIO(
            ID_PEDIDO,ID_PRODUTO, QUANTIDADE , PRECO_UNITARIO
        )
        VALUES (
            P_ID_PEDIDO,P_ID_PRODUTO, P_QUANTIDADE , V_PRECO
        );
        SELECT 'ITEM ADICIONADO' AS MENSAGEM;
    END IF;
END$$

DELIMITER;

CALL ADICIONAR_ITEM_PEDIDO(1,1,2);

